/* Run with Node: node tests.js */
const fs=require('fs'),M=require('../../rotary_melter/web/calculations/Calculation.js');
let checks=[];function check(name,ok,data){checks.push({name,passed:!!ok,data});if(!ok)throw Error(name+' failed: '+JSON.stringify(data));}
const base=M.simulate({});
check('Analytic product energy (25 to 75 C)',Math.abs(base.productEnergyKWh-14.9925)<1e-9,base.productEnergyKWh);
check('Energy conservation, default',Math.abs(base.balanceJ)<.1,base.balanceJ);
const half=M.simulate({dt:.5});
check('Time step convergence target',Math.abs(base.seconds-half.seconds)/half.seconds<.001,{base:base.seconds,half:half.seconds});
check('Time step convergence loss',Math.abs(base.lossKWh-half.lossKWh)/half.lossKWh<.001,{base:base.lossKWh,half:half.lossKWh});
const noLoss=M.simulate({externalH:0,emissivity:0,extraUA:0});
check('Adiabatic outside loss',Math.abs(noLoss.lossKWh)<1e-12,noLoss.lossKWh);
check('Adiabatic energy conservation',Math.abs(noLoss.balanceJ)<.1,noLoss.balanceJ);
const insulated=M.simulate({insulation:50});
check('Insulation reduces integrated loss',insulated.lossKWh<base.lossKWh,{bare:base.lossKWh,insulated:insulated.lossKWh});
const fixed=M.simulate({rpmMode:0}),rpm=M.simulate({rpmMode:0,rpm:50});
check('Fixed mode is RPM invariant',rpm.seconds===fixed.seconds&&rpm.lossKWh===fixed.lossKWh,{rpm10:fixed.seconds,rpm50:rpm.seconds});
check('316 thermal conductivity reference',M.defaults.steelK===16.2,M.defaults.steelK);
check('Scenario at zero rpm equals static h',M.rpmHeatTransfer({...M.defaults,rpm:0})===40,M.rpmHeatTransfer({...M.defaults,rpm:0}));
check('Scenario at reference rpm equals reference h',M.rpmHeatTransfer(M.defaults)===100,M.rpmHeatTransfer(M.defaults));
check('Scenario h is bounded by explicit cap',M.rpmHeatTransfer({...M.defaults,rpm:10000})===300,M.rpmHeatTransfer({...M.defaults,rpm:10000}));
const stationary=M.simulate({rpm:0}),faster=M.simulate({rpm:20});
check('Declared scenario changes melt duration',stationary.seconds>base.seconds&&base.seconds>faster.seconds,{rpm0:stationary.seconds,rpm10:base.seconds,rpm20:faster.seconds});
check('RPM scenario conserves energy',Math.abs(faster.balanceJ)<.1,faster.balanceJ);
check('Inclined normal Froude ratio',Math.abs(M.rotation(M.defaults).frNormal-M.rotation(M.defaults).fr/Math.cos(Math.PI/4))<1e-12,M.rotation(M.defaults));
check('Vertical axis normal Froude undefined',M.rotation({...M.defaults,angle:90}).frNormal===null,true);
const legacy=M.migrateInputs({version:'1.0',inputs:{rpm:10,href:100,rpmGain:0,steelK:16}});
check('Old JSON retains old RPM behavior',legacy.rpmMode===0&&legacy.steelK===16&&M.rpmHeatTransfer(legacy)===100,legacy.rpmMode);
const restored=M.migrateInputs({version:'1.1',inputs:M.defaults});
check('New JSON retains new RPM behavior',restored.rpmMode===1&&restored.steelK===16.2,restored.rpmMode);
const cold=M.simulate({waterInitial:25,boiler:5,sourceMode:0});
check('Boiler thermal power cap',cold.peakKW<=5*.95+1e-8,cold.peakKW);
check('Supply cannot exceed setpoint',cold.hist.every(p=>p.waterIn<=110+1e-7),Math.max(...cold.hist.map(p=>p.waterIn)));
check('Cold start energy conservation',Math.abs(cold.balanceJ)<.1,cold.balanceJ);
const ideal=M.simulate({sourceMode:1});
check('Ideal source holds inlet setpoint',ideal.hist.every(p=>Math.abs(p.waterIn-110)<1e-6),ideal.hist[10].waterIn);
check('Wax 180 kg fails default volume allowance',!base.g.feasible,base.g.maxMass);
check('100 kg fits default volume allowance',M.geometry({...M.defaults,mass:100}).feasible,true);
check('Saturation pressure 110 C',Math.abs(M.psat(110)-1.4338)<.002,M.psat(110));
let invalid=false;try{M.simulate({packing:0});}catch(e){invalid=true;}check('Reject invalid packing',invalid,true);
const sizing=M.sizeBoiler({...M.defaults,mass:100,goalHours:2});
check('Sizing finds conditional feasible power',sizing.possible&&sizing.kw>0,sizing.kw);
const sized=M.simulate({...M.defaults,mass:100,boiler:sizing.kw,maxHours:2,sourceMode:0});
check('Sized power reaches target',sized.targetReached,sized.seconds);
const impossible=M.sizeBoiler({...M.defaults,goalHours:.05});check('Impossible target not assigned finite boiler',!impossible.possible,impossible);
const warm=M.simulate({initial:65,target:75});
check('Initially liquid has zero melting time',warm.meltingTime===0,warm.meltingTime);
const output={date:'2026-10-19',scope:'Numerical checks; not experimental validation',checks,defaultResults:{hours:base.seconds/3600,productKWh:base.productEnergyKWh,lossKWh:base.lossKWh,capacityKg:base.g.maxMass,energyBalanceJ:base.balanceJ}};
fs.writeFileSync('validation.json',JSON.stringify(output,null,2));console.log(JSON.stringify(output,null,2));
